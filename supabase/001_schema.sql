-- ==== PLANIFICATION (pg_cron) ====
-- Purge quotidienne : chaque heure, à la minute 15, supprime les commandes d'avant aujourd'hui (fuseau Europe/Paris)
-- et leurs lignes, ainsi que les sessions expirées. Les comptes clients ne sont pas touchés.
-- L'extension pg_cron est activée ici si elle ne l'est pas déjà (sinon : Database > Extensions > pg_cron).
create extension if not exists pg_cron with schema pg_catalog;

select cron.schedule(
  'purge-orders-hors-jour',
  '15 * * * *',
  $cron$
  DELETE FROM public.order_items WHERE order_id IN (SELECT id FROM public.orders WHERE created_at < to_char((date_trunc('day', now() at time zone 'Europe/Paris') at time zone 'Europe/Paris') at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"'));
  DELETE FROM public.orders WHERE created_at < to_char((date_trunc('day', now() at time zone 'Europe/Paris') at time zone 'Europe/Paris') at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"');
  DELETE FROM public.sessions WHERE expires_at < to_char(now() at time zone 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS"Z"');
  $cron$
);
